import { NextRequest, NextResponse } from "next/server";

export const dynamic = "force-dynamic";

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

type Params = { width?: number; height?: number; thickness?: number; dia?: number; length?: number; flange?: number; web?: number; loadKg?: number };

function plateLisp(p: Params, prompt: string): string {
  const w = p.width ?? 150;
  const h = p.height ?? 150;
  const th = p.thickness ?? 3;
  return `;;; ============================================================
;;; AutoLISP — Mounting Plate
;;; Prompt: ${prompt}
;;; Generated by NCT CAD · Prompt-to-AutoCAD engine
;;; ============================================================
(defun c:LKL-PLATE ( / w h th pt1 pt2)
  (setq w   ${w}
        h   ${h}
        th  ${th}
        pt1 (getpoint "\\nSpecify insertion point: ")
        pt2 (list (+ (car pt1) w) (+ (cadr pt1) h)))
  (command "_.RECTANG" pt1 pt2)
  ;; 4x M10 mounting holes, 15mm from each edge
  (command "_.CIRCLE" (list (+ (car pt1) 15) (+ (cadr pt1) 15))  "5")
  (command "_.CIRCLE" (list (- (car pt2) 15) (+ (cadr pt1) 15))  "5")
  (command "_.CIRCLE" (list (+ (car pt1) 15) (- (cadr pt2) 15))  "5")
  (command "_.CIRCLE" (list (- (car pt2) 15) (- (cadr pt2) 15))  "5")
  ;; Hatch the plate outline to indicate thickness ${th}mm
  (command "_.-HATCH" "_S" (entlast) "" "")
  (princ (strcat "\\nPlate " (itoa w) "x" (itoa h) "x" (itoa th) "mm created."))
  (princ)
)
(princ "\\nType LKL-PLATE to run.")`;
}

function lbracketLisp(p: Params, prompt: string): string {
  const w = p.width ?? 100;
  const h = p.height ?? 80;
  const th = p.thickness ?? 3;
  const fl = p.flange ?? 40;
  return `;;; ============================================================
;;; AutoLISP — L-Bracket
;;; Prompt: ${prompt}
;;; Generated by NCT CAD · Prompt-to-AutoCAD engine
;;; ============================================================
(defun c:LKL-LBRACKET ( / w h th fl pt0 pt1 pt2 pt3 pt4 pt5)
  (setq w   ${w}
        h   ${h}
        th  ${th}
        fl  ${fl}
        pt0 (getpoint "\\nSpecify insertion point: ")
        pt1 pt0
        pt2 (list (+ (car pt0) w) (cadr pt0))
        pt3 (list (+ (car pt0) w) (+ (cadr pt0) th))
        pt4 (list (+ (car pt0) th) (+ (cadr pt0) th))
        pt5 (list (+ (car pt0) th) (+ (cadr pt0) h))
        pt6 (list (car pt0) (+ (cadr pt0) h)))
  (command "_.PLINE" pt1 pt2 pt3 pt4 pt5 pt6 "_C")
  ;; Mounting slots
  (command "_.CIRCLE" (list (+ (car pt0) (/ fl 2)) (+ (cadr pt0) (/ th 2))) "5.5")
  (command "_.CIRCLE" (list (+ (car pt0) (/ th 2)) (+ (cadr pt0) (- h (/ fl 2)))) "5.5")
  (princ (strcat "\\nL-Bracket " (itoa w) "x" (itoa h) "x" (itoa th) "mm created."))
  (princ)
)
(princ "\\nType LKL-LBRACKET to run.")`;
}

function castorLisp(p: Params, prompt: string): string {
  const dia = p.dia ?? 75;
  const load = p.loadKg ?? 60;
  return `;;; ============================================================
;;; AutoLISP — Castor Wheel Mount
;;; Prompt: ${prompt}
;;; Generated by NCT CAD · Prompt-to-AutoCAD engine
;;; ============================================================
(defun c:LKL-CASTOR ( / dia load pt0 pt1 pt2)
  (setq dia   ${dia}
        load  ${load}
        pt0   (getpoint "\\nSpecify castor centre: "))
  ;; Wheel circle
  (command "_.CIRCLE" pt0 (rtos (/ dia 2.0) 2 2))
  ;; Hub
  (command "_.CIRCLE" pt0 "8")
  ;; Mounting plate 60x60 centred on pt0
  (command "_.RECTANG"
    (list (- (car pt0) 30) (- (cadr pt0) 30))
    (list (+ (car pt0) 30) (+ (cadr pt0) 30)))
  ;; 4x bolt holes
  (command "_.CIRCLE" (list (- (car pt0) 22) (- (cadr pt0) 22)) "4.5")
  (command "_.CIRCLE" (list (+ (car pt0) 22) (- (cadr pt0) 22)) "4.5")
  (command "_.CIRCLE" (list (- (car pt0) 22) (+ (cadr pt0) 22)) "4.5")
  (command "_.CIRCLE" (list (+ (car pt0) 22) (+ (cadr pt0) 22)) "4.5")
  (princ (strcat "\\nCastor Ø" (itoa dia) "mm, rated ${load}kg, created."))
  (princ)
)
(princ "\\nType LKL-CASTOR to run.")`;
}

function ivpoleLisp(p: Params, prompt: string): string {
  const len = p.length ?? 2500;
  const dia = p.dia ?? 50;
  return `;;; ============================================================
;;; AutoLISP — IV Pole (Medical Equipment)
;;; Prompt: ${prompt}
;;; Generated by NCT CAD · Prompt-to-AutoCAD engine
;;; ============================================================
(defun c:LKL-IVPOLE ( / len dia pt0 pt1 pt2 pt3)
  (setq len ${len}
        dia ${dia}
        pt0 (getpoint "\\nSpecify base centre: ")
        pt1 (list (car pt0) (+ (cadr pt0) len))
        pt2 (list (+ (car pt0) (/ dia 2.0)) (cadr pt0))
        pt3 (list (- (car pt0) (/ dia 2.0)) (cadr pt0)))
  ;; Vertical pole
  (command "_.RECTANG" pt3 (list (+ (car pt0) (/ dia 2.0)) (+ (cadr pt0) len)))
  ;; 5-star base (approximate with 5 circles around base)
  (setq ang 0)
  (while (< ang (* 2 PI))
    (command "_.CIRCLE"
      (list (+ (car pt0) (* 120 (cos ang))) (+ (cadr pt0) (* 120 (sin ang))))
      "20")
    (setq ang (+ ang (/ (* 2 PI) 5))))
  ;; Hook at top
  (command "_.ARC" (list (- (car pt0) 30) (cadr pt1))
                  (list (car pt0) (+ (cadr pt1) 30))
                  (list (+ (car pt0) 30) (cadr pt1)))
  (princ (strcat "\\nIV Pole Ø" (itoa dia) "mm × ${len}mm tall, created."))
  (princ)
)
(princ "\\nType LKL-IVPOLE to run.")`;
}

export async function POST(req: NextRequest) {
  const body = await req.json().catch(() => ({}));
  const type: string = String(body.type || "plate");
  const params: Params = body.params ?? {};
  const prompt: string = String(body.prompt || "").trim();
  const lang: "en" | "bm" = body.lang === "bm" ? "bm" : "en";
  await sleep(500);

  let code = "";
  let title = "";
  if (type === "plate") {
    code = plateLisp(params, prompt);
    title = lang === "bm" ? "Plat Pemasangan" : "Mounting Plate";
  } else if (type === "lbracket") {
    code = lbracketLisp(params, prompt);
    title = lang === "bm" ? "Penyangak L" : "L-Bracket";
  } else if (type === "castor") {
    code = castorLisp(params, prompt);
    title = lang === "bm" ? "Roda Castor" : "Castor Wheel";
  } else if (type === "ivpole") {
    code = ivpoleLisp(params, prompt);
    title = lang === "bm" ? "Tiang IV" : "IV Pole";
  } else {
    return NextResponse.json({ error: "Unknown part type" }, { status: 400 });
  }

  const lines = code.split("\n").length;
  const commands = (code.match(/\(command /g) || []).length;
  return NextResponse.json({
    ok: true,
    type,
    title,
    code,
    summary: {
      lines,
      commands,
      params,
      lang,
    },
  });
}
